CREATE TABLE IF NOT EXISTS pickem_matches (
  id INTEGER PRIMARY KEY,
  week INTEGER NOT NULL,
  scheduled_at INTEGER NOT NULL,
  home_key TEXT NOT NULL,
  away_key TEXT NOT NULL,
  home_score INTEGER,
  away_score INTEGER,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS pickem_matches_by_week ON pickem_matches(week);

CREATE TABLE IF NOT EXISTS picks (
  discord_id TEXT NOT NULL REFERENCES users(discord_id) ON DELETE CASCADE,
  match_id INTEGER NOT NULL REFERENCES pickem_matches(id) ON DELETE CASCADE,
  choice TEXT NOT NULL CHECK (choice IN ('home', 'draw', 'away')),
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (discord_id, match_id)
);

CREATE INDEX IF NOT EXISTS picks_by_match ON picks(match_id);

CREATE TABLE IF NOT EXISTS pickem_tiebreakers (
  discord_id TEXT NOT NULL REFERENCES users(discord_id) ON DELETE CASCADE,
  week INTEGER NOT NULL,
  goals INTEGER NOT NULL CHECK (goals BETWEEN 0 AND 99),
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (discord_id, week)
);

