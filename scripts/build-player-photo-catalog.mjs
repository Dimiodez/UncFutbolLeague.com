// Generate the server allowlist from the existing player directories, not uploads.
import {readFile,writeFile} from 'node:fs/promises';
import vm from 'node:vm';
const context=vm.createContext({});
const pages=await readFile('league-pages.js','utf8');
vm.runInContext(await readFile('league-season2.js','utf8')+'\n'+await readFile('player-portraits.js','utf8')+'\n'+pages.slice(pages.indexOf('const leaguePlayerReference ='),pages.indexOf('const leagueStatCategories'))+'\n;globalThis.catalogPlayers=[...leaguePlayerReference,...Object.values(leagueProvisionalSeasons).flatMap(s=>s.players)];globalThis.portraitAliases=leaguePlayerPortraits;',context);
const entries={};
for(const player of context.catalogPlayers){
  const id=String(player.id),alias=context.portraitAliases.find(a=>a.playerIds.includes(id));
  entries[id]={id,name:player.name,identity:alias?alias.playerIds[0]:id};
}
await writeFile('functions/_lib/player-photo-catalog.js',`// Generated by scripts/build-player-photo-catalog.mjs; known directory IDs only.\nexport const PLAYER_PHOTO_CATALOG = ${JSON.stringify(entries,null,2)};\n`);
